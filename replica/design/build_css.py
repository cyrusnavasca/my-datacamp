#!/usr/bin/env python3
"""Generate tokens.css (CSS variables + Tailwind v4 @theme mapping) from tokens.json and tokens.dark.json.

    python3 replica/design/build_css.py [out_path]
"""
import json, pathlib, sys

here = pathlib.Path(__file__).parent
light = json.loads((here / "tokens.json").read_text())
dark = json.loads((here / "tokens.dark.json").read_text())
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "tokens.css"

def color_vars(colors, indent="  "):
    return "\n".join(f"{indent}--c-{k}: {v};" for k, v in colors.items())

dark_only = {k: v for k, v in dark["color"].items() if light["color"].get(k) != v}
lines = ["/* Generated by replica/design/build_css.py from tokens.json. Do not edit by hand. */", ":root {",
         color_vars(light["color"]), "  color-scheme: light;", "}",
         '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {',
         color_vars(dark_only, "    "), "    color-scheme: dark;", "  }", "}",
         ':root[data-theme="dark"] {', color_vars(dark_only), "  color-scheme: dark;", "}", "",
         "@theme inline {"]
lines += [f"  --color-{k}: var(--c-{k});" for k in light["color"]]
lines += [f'  --font-sans: {light["font"]["sans"]};', f'  --font-mono: {light["font"]["mono"]};']
for k, v in light["radius"].items():
    lines.append(f"  --radius-{k}: {v}px;")
for k, v in light["shadow"].items():
    lines.append(f"  --shadow-{k}: {v};")
for k, t in light["type"].items():
    lines.append(f"  --text-{k}: {t['size']/16:g}rem;")
    lines.append(f"  --text-{k}--line-height: {t['line']/16:g}rem;")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
